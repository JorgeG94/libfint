#!/usr/bin/env python3
"""Generate fortran/test/ecp_check.F90 from PySCF.

    python3 fortran/test/gen_ecp_check.py

Every other check in this suite compares against libcint at run time, by
linking the fetched C.  This one cannot: libcint has no ECP code, so there is
nothing to link.  The reference is PySCF's `mol.intor('ECPscalar_sph')`, and it
has to be baked in.

That makes the choice of system load-bearing, because a committed reference is
only ever as good as what it covers.  Cu/H in LANL2DZ is small enough for the
values to fit in a source file and still exercises what matters:

  * a local (l = -1) channel and three projected channels, so both ECP terms;
  * s, p and d orbital shells, so the Cartesian-to-spherical transform runs on
    a shell where it is not the identity;
  * contracted shells, so the primitive loops and the coefficient scaling are
    not trivially one-deep;
  * an atom with no ECP beside one with, so the screen has to reject as well
    as accept.

The tolerance is not bit-identity.  cint_ecp_rad explains why in full: the C
evaluates its modified spherical Bessel function through a 400-entry
interpolation table and this port evaluates the series, so results differ in
the last two or three bits and that difference propagates.

The tolerance is stated against the largest element of the matrix rather than
element by element, because that is how the error actually behaves.  Measured
across seven ECP systems -- Cu, Au and W in LANL2DZ, I and Ba in def2-SVP, Pt
and Hg in def2-TZVP -- the disagreement runs between 7.8e-17 and 1.8e-14 of
the largest element, whose own magnitude ranges from 3 to 308.  In absolute
terms that is 5.6e-16 on the smallest of those systems and 2.0e-13 on the
largest, which is why a fixed absolute bound would be either wrong or useless.

TOL is set at 1e-11, about three orders above the worst measured value.  The
slack is deliberate: the radial refinement stops on a convergence test, so a
pair that sits near that threshold can take a different number of levels here
than in the C and land further out than the systems below ever do.

A purely element-wise relative test would be the wrong instrument.  On Au2 one
element of magnitude 5e-6 carries an absolute error of 5e-14, which reads as a
relative error of 1.1e-08 -- meaningless as an accuracy claim, and enough to
fail any relative bound tight enough to be worth setting.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

GEOM = "Cu 0 0 0; H 0 0 2.0"
BASIS = "lanl2dz"
ECP = "lanl2dz"


def wrap(values, indent="      ", per_line=3):
    out, line = [], []
    for i, v in enumerate(values):
        line.append(v)
        if len(line) == per_line or i == len(values) - 1:
            out.append(indent + ", ".join(line))
            line = []
    return ", &\n".join(out)


def main():
    import numpy as np
    from pyscf import gto

    mol = gto.M(atom=GEOM, basis=BASIS, ecp=ECP, verbose=0)
    ref = mol.intor("ECPscalar_sph")          # also fills env[18], env[19]
    bas = np.vstack((mol._bas, mol._ecpbas))
    env = mol._env
    atm = np.asarray(mol._atm)
    ao_loc = mol.ao_loc_nr()

    src = TEMPLATE % {
        "geom": GEOM,
        "basis": BASIS,
        "pyscf_version": __import__("pyscf").__version__,
        "natm": mol.natm,
        "nbas_all": bas.shape[0],
        "nbas": mol.nbas,
        "nenv": len(env),
        "nao": mol.nao_nr(),
        "atm": wrap([str(int(x)) for x in atm.ravel()], per_line=12),
        "bas": wrap([str(int(x)) for x in bas.ravel()], per_line=12),
        "env": wrap(["%.17e_dp" % v for v in env]),
        "ao_loc": wrap([str(int(x)) for x in ao_loc], per_line=12),
        "ref": wrap(["%.17e_dp" % v for v in ref.ravel(order="F")]),
    }
    path = os.path.join(HERE, "ecp_check.F90")
    with open(path, "w") as fh:
        fh.write(src)
    print("%dx%d ECP matrix -> ecp_check.F90" % (ref.shape[0], ref.shape[0]))


TEMPLATE = '''!
! The scalar ECP integrals against PySCF.
!
! GENERATED by fortran/test/gen_ecp_check.py -- do not edit.
! Reference: PySCF %(pyscf_version)s, mol.intor('ECPscalar_sph')
! System:    %(geom)s in %(basis)s with the matching ECP
!
! The reference is PySCF and not libcint because libcint has no ECP code --
! cint_ecp and its supporting modules are translated from
! pyscf/lib/gto/nr_ecp.c.  There is nothing to link against at run time, so
! unlike the rest of this suite the reference is committed.
!
! The tolerance is not bit-identity, and cint_ecp_rad says why: the C reaches
! its modified spherical Bessel function through a 400-entry interpolation
! table, this port evaluates the series, and the two differ in the last few
! bits.
!
! It is stated against the largest element rather than element by element,
! because that is how the error behaves: across seven ECP systems it runs
! between 7.8e-17 and 1.8e-14 of the largest element, which is itself between
! 3 and 308 depending on the basis.  An element-wise relative bound would
! instead be dominated by near-zero elements, where 5e-14 of absolute error
! on a value of 5e-6 reads as 1.1e-08 and means nothing.
!
! What the system covers: a local channel and three projected ones, so both
! ECP terms; s, p and d shells, so the spherical transform is not an
! identity; contracted shells; and a second atom carrying no ECP, so the
! overlap screen has to reject as well as accept.
!
program ecp_check
   use cint_const, only: dp
   use cint_bas, only: ANG_OF, NCTR_OF, BAS_SLOTS
   use cint_ecp_drv, only: ecp_scalar_sph
   implicit none

   integer, parameter :: NATM = %(natm)d
   integer, parameter :: NBAS_ALL = %(nbas_all)d
   integer, parameter :: NBAS = %(nbas)d
   integer, parameter :: NENV = %(nenv)d
   integer, parameter :: NAO = %(nao)d
   !> Relative to the largest element of the matrix, not to each element
   real(dp), parameter :: TOL = 1.0e-11_dp

   integer, parameter :: ATM(0:NATM*6 - 1) = [ &
%(atm)s]

   integer, parameter :: BAS(0:NBAS_ALL*BAS_SLOTS - 1) = [ &
%(bas)s]

   integer, parameter :: AO_LOC(0:NBAS) = [ &
%(ao_loc)s]

   real(dp), parameter :: ENV(0:NENV - 1) = [ &
%(env)s]

   real(dp), parameter :: REF(NAO*NAO) = [ &
%(ref)s]

   real(dp) :: mat(NAO, NAO)
   real(dp), allocatable :: blk(:)
   real(dp) :: worst, wabs, d, denom, scale
   integer :: ish, jsh, di, dj, i0, j0, i, r, cc, hv, nbad

   mat = 0.0_dp
   do ish = 0, NBAS - 1
      do jsh = 0, NBAS - 1
         di = (2*BAS(ANG_OF + ish*BAS_SLOTS) + 1)*BAS(NCTR_OF + ish*BAS_SLOTS)
         dj = (2*BAS(ANG_OF + jsh*BAS_SLOTS) + 1)*BAS(NCTR_OF + jsh*BAS_SLOTS)
         allocate (blk(0:di*dj - 1))
         blk = 0.0_dp
         hv = ecp_scalar_sph(blk, [ish, jsh], ATM, NATM, BAS, NBAS, ENV)
         i0 = AO_LOC(ish)
         j0 = AO_LOC(jsh)
         do i = 0, dj - 1
            mat(i0 + 1:i0 + di, j0 + 1 + i) = blk(i*di:i*di + di - 1)
         end do
         deallocate (blk)
      end do
   end do

   worst = 0.0_dp
   wabs = 0.0_dp
   scale = 0.0_dp
   nbad = 0
   do cc = 1, NAO
      do r = 1, NAO
         scale = max(scale, abs(REF((cc - 1)*NAO + r)))
      end do
   end do
   ! A matrix of zeros would make the test vacuous rather than passing, which
   ! is a mistake worth failing on: asking for an ECP the basis does not
   ! define gives exactly that, and it looks like perfect agreement.
   if (scale <= 0.0_dp) then
      write (*, '(a)') "ecp_check: FAILED -- the reference matrix is identically zero"
      stop 1
   end if

   do cc = 1, NAO
      do r = 1, NAO
         denom = REF((cc - 1)*NAO + r)
         d = abs(mat(r, cc) - denom)
         wabs = max(wabs, d)
         if (abs(denom) > 1.0e-12_dp) then
            if (d/abs(denom) > worst) worst = d/abs(denom)
         else if (d > TOL*scale) then
            ! An element PySCF says is zero and this one does not: a screen
            ! that rejected a pair it should have kept would show up here and
            ! nowhere in the measure above.
            nbad = nbad + 1
         end if
      end do
   end do

   write (*, '(a,i0,a,i0,a)') "ecp_check: ", NAO, "x", NAO, " ECPscalar_sph"
   write (*, '(a,es12.4)') "  largest reference element     : ", scale
   write (*, '(a,es12.4)') "  worst absolute                : ", wabs
   write (*, '(a,es12.4)') "  worst / largest element       : ", wabs/scale
   write (*, '(a,es12.4)') "  worst element-wise relative   : ", worst
   write (*, '(a,i0)') "  elements zero in PySCF, not here: ", nbad

   if (wabs/scale > TOL .or. nbad > 0) then
      write (*, '(a)') "ecp_check: FAILED"
      stop 1
   end if
   write (*, '(a)') "ecp_check: OK"
end program ecp_check
'''


if __name__ == "__main__":
    sys.exit(main())
