#!/usr/bin/env python3
"""Generate fortran/test/catalogue_check.F90.

    python3 fortran/test/gen_catalogue_check.py <build-dir>

536 entry points is 536 interface blocks, and writing those by hand is 536
chances to mistype a component count.  A count that is too small overruns the
buffer -- which is a segfault if you are lucky and silence if you are not, and
during development it was both.

So the counts are read out of the generated Fortran modules, from each
integral's own ng array, and the buffer is sized from an upper bound rather
than from the exact figure.  The three drivers do not agree on how many blocks
they write:

    CINT1e_drv          ncomp_e1 * ncomp_tensor
    CINT2e_drv          ncomp_e1 * ncomp_e2 * ncomp_tensor
    CINT3c2e_drv        ncomp_e1 * ncomp_tensor
    CINT1e_spinor_drv   ncomp_tensor
    CINT2e_spinor_drv   ncomp_tensor
    CINT3c2e_spinor_drv ncomp_e2 * ncomp_tensor

and the product of all three slots bounds every one of them -- EXCEPT that the
rinv family (nuc, rinv, nabla-rinv) sets ng[POS_E2] to zero, so that product is
zero and bounds nothing.  Reading it as a bound gave a zero-length buffer for
int1e_ipipipnuc and twenty-seven blocks written into it, which corrupted the
heap and then aborted somewhere else entirely.  The bound clamps each slot to
at least one and never goes below the exact count.  The comparison still uses
the exact count, so nothing is checked twice or skipped.

Only entry points the C actually exports are emitted; nm on the built library
is the authority, not a list kept by hand.
"""

import collections
import glob
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# How many blocks each driver writes, in terms of the ng slots (5, 6, 7).
BLOCKS = {
    "cint_1e_drv":         lambda ng: ng[5] * ng[7],
    "cint_2e_drv":         lambda ng: ng[5] * ng[6] * ng[7],
    "cint_3c2e_drv":       lambda ng: ng[5] * ng[7],
    "cint_2c2e_drv":       lambda ng: ng[5] * ng[6] * ng[7],
    "cint_1e_spinor_drv":  lambda ng: ng[7],
    "cint_2e_spinor_drv":  lambda ng: ng[7],
    "cint_3c2e_spinor_drv":lambda ng: ng[6] * ng[7],
    "cint_3c1e_drv":       lambda ng: ng[5] * ng[7],
    "cint_1e_grids_drv":   lambda ng: ng[5] * ng[7],
}
ARITY = {"cint_1e_drv": 1, "cint_1e_spinor_drv": 1,
         "cint_2e_drv": 4, "cint_2e_spinor_drv": 4,
         "cint_3c2e_drv": 3, "cint_3c2e_spinor_drv": 3,
         "cint_2c2e_drv": 2,
         "cint_3c1e_drv": 3,
         # the grids "third index" is the grid list, not a shell, so these two
         # are driven separately by grids_check and spinor_grids_check
         "cint_1e_grids_drv": 0,
         "cint_1e_grids_spinor_drv": 0}


def collect(builddir):
    out = subprocess.run(["nm", "-D", "--defined-only", os.path.join(builddir, "libcint.so")],
                         capture_output=True, text=True).stdout
    exported = {p[2] for p in (l.split() for l in out.splitlines())
                if len(p) >= 3 and p[1] == "T"}

    entries = []
    for path in sorted(glob.glob(os.path.join(ROOT, "src/cint_gen_*.f90"))):
        mod = os.path.basename(path)[:-4]
        src = open(path).read()
        for m in re.finditer(r"function (\w+)_(cart|sph|spinor)\(out, dims.*?"
                             r"ng\(0:7\) = \[([^\]]+)\].*?has_value = (\w+)\(",
                             src, re.S):
            name, form, drv = m.group(1), m.group(2), m.group(4)
            ng = [int(x) for x in m.group(3).split(",")]
            if f"{name}_{form}" not in exported:
                continue
            if drv not in ARITY:
                raise SystemExit(
                    "%s: driver %r is not in ARITY.\n"
                    "A new driver was added to the port without teaching this\n"
                    "generator its arity, so the catalogue would silently skip\n"
                    "every entry point on it.  Add it above." % (name, drv))
            if ARITY[drv] == 0:
                continue          # grids: their own checks drive those
            entries.append(dict(mod=mod, name=name, form=form, drv=drv,
                                ng=ng, nc=BLOCKS[drv](ng),
                                bound=max(BLOCKS[drv](ng),
                                          max(ng[5], 1) * max(ng[6], 1) * max(ng[7], 1)),
                                arity=ARITY[drv]))
    return entries


HEAD = '''!
! D10 acceptance: every generated entry point against the C.
!
! {n} of them -- {ncart} Cartesian, {nsph} spherical, {nspinor} spinor -- across the
! whole of auto_intor.cl: gradients, Hessians, third and fourth derivatives,
! GIAO, DKB, LRESC, Gaunt, Breit, and the three- and two-centre families.  Both
! sides come from the same descriptions; only the emitter differs.
!
! GENERATED by fortran/test/gen_catalogue_check.py -- do not edit.  The reasons
! are in that file's docstring, and the short version is that the three drivers
! disagree about how many blocks they write, so the buffer is sized from an
! upper bound and the comparison uses the exact count.
!
! The auxiliary index of a three-centre SPINOR integral is spherical, not
! spinor: the fitting basis carries no spin, so CINT3c2e_spinor_drv counts it
! as 2k+1.  Using the spinor count there does not crash -- it is larger -- it
! just compares the wrong elements, which reads exactly like a broken
! transform.
!
! The sweep is deliberately coarse: two bases and a wide stride.  What it looks
! for is a systematically wrong emitter, and that shows on the first shell pair
! it reaches.  The narrow, exhaustive sweeps live in the other checks, over the
! integrals a caller actually uses.
!
! The bar is the usual one: bit-identical up to five Rys roots, 1e-11 above,
! with the root count from each integral's own ng increments.
!
program catalogue_check
   use iso_c_binding
   use libcint_interface, only: ATM_SLOTS, BAS_SLOTS, PTR_ENV_START, ANG_OF, &
                                KAPPA_OF, CINTcgto_cart, CINTcgto_spheric, &
                                CINTcgto_spinor
   use cint_test_systems
   use cint_const, only: dp
   use cint_workspace, only: cint_ws
'''


def emit(entries, out):
    mods = sorted({e["mod"] for e in entries})
    forms = collections.Counter(e["form"] for e in entries)
    L = [HEAD.format(n=len(entries), ncart=forms["cart"],
                     nsph=forms["sph"], nspinor=forms["spinor"])]
    for m in mods:
        L.append(f"   use {m}")
    L.append("   implicit none\n")
    L.append("   interface")
    for e in entries:
        ty = "complex(c_double_complex)" if e["form"] == "spinor" else "real(c_double)"
        L.append(f"""      function c_{e['name']}_{e['form']}(o,d,s,a,na,b,nb,e,p,c) &
            bind(C,name='{e['name']}_{e['form']}') result(r)
         import :: c_int, c_double, c_double_complex, c_ptr
         {ty}::o(*); type(c_ptr),value::d,p,c
         integer(c_int)::s(*),a(*),b(*); integer(c_int),value::na,nb
         real(c_double)::e(*); integer(c_int)::r
      end function""")
    L.append("   end interface\n")
    L.append('''   integer(c_int), allocatable :: atm(:,:), bas(:,:)
   real(c_double), allocatable :: env(:)
   integer(c_int) :: nbas, off, i, j, k, l, shls(4), ret
   real(c_double), allocatable :: cr(:), fr(:)
   complex(c_double_complex), allocatable :: cz(:), fz(:)
   integer :: ib, di, dj, dk, dl, nq, nb2, dims(0:3), fshls(0:3), stride, ii
   integer :: ncmp, nbad, nexact, nchecked, nrpoly
   integer :: ng76
   real(dp) :: worst
   character(len=90) :: wat
   real(dp), parameter :: CANARY = 1.2345678901e300_dp
   complex(c_double_complex), parameter :: ZCANARY = cmplx(CANARY, -CANARY, dp)
   type(cint_ws) :: ws
   integer, allocatable :: fatm(:), fbas(:)
   real(dp), allocatable :: fenv(:)
   logical :: hv

   allocate(atm(ATM_SLOTS, 8), bas(BAS_SLOTS, 200), env(20000))
   ncmp = 0; nbad = 0; nexact = 0; nrpoly = 0
   ng76 = 0; nchecked = 0; worst = 0.0_dp; wat = "(none)"

   ! basis 1 is 6-31G (contracted, s and p); basis 3 is cc-pVDZ, which adds d
   ! and so the general 2D-to-4D path.  Between them every branch in the
   ! drivers is reached.
   do ii = 1, 2
      if (ii == 1) then; ib = 1; else; ib = 3; end if
      atm = 0; bas = 0; env = 0.0_c_double
      off = PTR_ENV_START
      call setup_c2h6_geometry(atm, env, off)
      call setup_reference_basis(ib, bas, env, nbas, off)
      allocate(fatm(0:47), fbas(0:8*int(nbas)-1), fenv(0:size(env)-1))
      do i = 1, 8
         fatm(6*(i-1):6*i-1) = int(atm(:, i))
      end do
      do i = 1, nbas
         fbas(8*(i-1):8*i-1) = int(bas(:, i))
      end do
      fenv = real(env, dp)

      stride = max(1, int(nbas)/2)
      do i = 0, nbas-1, stride
      do j = 0, nbas-1, stride
      do k = 0, nbas-1, stride
      do l = 0, nbas-1, stride
         shls(1)=i; shls(2)=j; shls(3)=k; shls(4)=l
         fshls(0)=i; fshls(1)=j; fshls(2)=k; fshls(3)=l
''')
    for e in entries:
        name, form, ar, nc, bound = e["name"], e["form"], e["arity"], e["nc"], e["bound"]
        dimfn = {"cart": "CINTcgto_cart", "sph": "CINTcgto_spheric",
                 "spinor": "CINTcgto_spinor"}[form]
        L.append(f"         di = int({dimfn}(i,bas)); dj = int({dimfn}(j,bas))")
        if ar >= 3:
            # the auxiliary index of a three-centre spinor integral is spherical
            kfn = "CINTcgto_spheric" if (form == "spinor" and ar == 3) else dimfn
            L.append(f"         dk = int({kfn}(k,bas))")
        if ar == 4:
            L.append(f"         dl = int({dimfn}(l,bas))")
        guard = "di > 0 .and. dj > 0"
        if ar >= 3: guard += " .and. dk > 0"
        if ar == 4: guard += " .and. dl > 0"
        L.append(f"         if ({guard}) then")
        base = {1: "di*dj", 2: "di*dj", 3: "di*dj*dk", 4: "di*dj*dk*dl"}[ar]
        dm = {1: "dims(0)=di; dims(1)=dj; dims(2)=1; dims(3)=1",
              2: "dims(0)=di; dims(1)=dj; dims(2)=1; dims(3)=1",
              3: "dims(0)=di; dims(1)=dj; dims(2)=dk; dims(3)=1",
              4: "dims(0)=di; dims(1)=dj; dims(2)=dk; dims(3)=dl"}[ar]
        kk = "k" if ar >= 3 else "0"
        ll = "l" if ar == 4 else "0"
        buf, cmpfn = ("cz", "cmpz") if form == "spinor" else ("cr", "cmpr")
        canary = "ZCANARY" if form == "spinor" else "CANARY"
        fbuf = "fz" if form == "spinor" else "fr"
        L.append(f"""         nq = {base}*{nc}; nb2 = {base}*{bound}; {dm}
         allocate({buf}(nb2), {fbuf}(nb2)); {buf}=0; {fbuf}=0
         ret = c_{name}_{form}({buf},c_null_ptr,shls,atm,8_c_int,bas,nbas,env,c_null_ptr,c_null_ptr)
         hv = {name}_{form}({fbuf},dims,fshls,fatm,8,fbas,int(nbas),fenv,ws)
         call {cmpfn}({buf}, {fbuf}, nq, "{name}_{form}", ib, i, j, {kk}, {ll}, &
                   [{','.join(str(x) for x in e['ng'][:4])}])
         deallocate({buf}, {fbuf})
         end if""")
    L.append('''      end do
      end do
      end do
      end do
      deallocate(fatm, fbas, fenv)
   end do

   print '(A,I0)',     "  entry points         : ", nchecked
   print '(A,I0)',     "  values compared      : ", ncmp
   print '(A,ES10.2)', "  worst diff / block   : ", worst
   print '(A,I0)',     "  inexact at <=5 roots : ", nexact
   print '(A,I0)',     "  r-poly last-bit      : ", nrpoly
   print '(A,I0)',     "  upstream g76 defect  : ", ng76
   print '(A,I0)',     "  over tolerance       : ", nbad
   if (ng76 > 0) then
      print '(A)', "  NOTE: the reference libcint is missing the g76 fix in"
      print '(A)', "        CINTgout1e_int3c1e_ip1_r6_origk (src/cint3c1e_a.c)."
      print '(A)', "        libfint is right and the C is wrong there; the"
      print '(A)', "        difference above is expected until that is merged."
      print '(A)', "        If this count is 0, delete the special case."
   end if
   if (nbad > 0 .or. nexact > 0) then
      print '(A,A)',   "  worst at             : ", trim(wat)
      stop 1
   end if
   print '(A)', "  RESULT: PASS"

contains

   subroutine overran(what, nb)
      character(len=*), intent(in) :: what
      integer, intent(in) :: nb
      print '(A,A,A,I0)', "  BUFFER OVERRUN by ", trim(what), " past ", nb
      stop 2
   end subroutine overran

   integer function rys_order(s1, s2, s3, s4, ic)
      integer, intent(in) :: s1, s2, s3, s4, ic(4)
      rys_order = (int(bas(ANG_OF,s1+1)) + ic(1) + int(bas(ANG_OF,s2+1)) + ic(2) &
                 + int(bas(ANG_OF,s3+1)) + ic(3) + int(bas(ANG_OF,s4+1)) + ic(4)) / 2 + 1
   end function rys_order

   subroutine note(r, nr, what, ibb, ii2, jj, kk, ll, m)
      real(dp), intent(in) :: r
      integer, intent(in) :: nr, ibb, ii2, jj, kk, ll, m
      character(len=*), intent(in) :: what
      real(dp) :: tol
      logical :: rpoly
      if (nr <= 5) then
         tol = 0.0_dp
      else
         tol = 1.0e-11_dp
      end if
      ! The ten r-polynomial families are the one place where the C hand-writes
      ! a kernel the generator would otherwise emit (src/cint1e_a.c,
      ! src/cint3c1e_a.c).  The two forms sum the same ten products in the same
      ! order, but the C folds each coefficient into the product -- 3*a*b*c,
      ! multiplying by three first -- where the generated form materialises the
      ! product into s[] and scales afterwards, 3*(a*b*c).  Three is not an
      ! exact multiplier here, so the two disagree in the last bit.  Nothing
      ! else about them differs: the port is bit-identical to the generator's
      ! own C output for these, and both agree with a finite difference of
      ! int3c1e_r6_origk to 2.6e-13.
      rpoly = index(what, "_r2_orig") > 0 .or. index(what, "_r4_orig") > 0 .or. &
              index(what, "_r6_orig") > 0
      if (rpoly) tol = max(tol, 1.0e-14_dp)
      ! CINTgout1e_int3c1e_ip1_r6_origk reads a g block it never writes, so an
      ! unpatched libcint returns a wrong value here.  Counted rather than
      ! tolerated: this is the C being wrong, not the two disagreeing, and the
      ! count is how you find out the fix has landed upstream.
      if (index(what, "int3c1e_ip1_r6_orig") > 0 .and. r > tol) then
         ng76 = ng76 + 1
         return
      end if
      if (r > worst) worst = r
      if (r > tol) then
         nbad = nbad + 1
         if (nbad == 1) write(wat,'(A,A,I0,A,I0,A,I0,A,I0,A,I0,A,I0,A,I0)') trim(what), &
            " basis=", ibb, " shls (",ii2,",",jj,",",kk,",",ll,") m=", m, " roots=", nr
      end if
      if (r /= 0.0_dp .and. nr <= 5) then
         if (rpoly) then
            nrpoly = nrpoly + 1
         else
            nexact = nexact + 1
         end if
      end if
   end subroutine note

   subroutine cmpr(c, f, n, what, ibb, ii2, jj, kk, ll, ic)
      real(dp), intent(in) :: c(:), f(:)
      integer, intent(in) :: n, ibb, ii2, jj, kk, ll, ic(4)
      character(len=*), intent(in) :: what
      integer :: m, nr
      real(dp) :: scal
      if (n <= 0) return
      nchecked = nchecked + 1
      nr = rys_order(ii2, jj, kk, ll, ic)
      scal = maxval(abs(c(1:n)))
      if (scal <= 0.0_dp) scal = 1.0_dp
      do m = 1, n
         ncmp = ncmp + 1
         call note(abs(c(m)-f(m))/scal, nr, what, ibb, ii2, jj, kk, ll, m)
      end do
   end subroutine cmpr

   subroutine cmpz(c, f, n, what, ibb, ii2, jj, kk, ll, ic)
      complex(dp), intent(in) :: c(:), f(:)
      integer, intent(in) :: n, ibb, ii2, jj, kk, ll, ic(4)
      character(len=*), intent(in) :: what
      integer :: m, nr
      real(dp) :: scal
      if (n <= 0) return
      nchecked = nchecked + 1
      nr = rys_order(ii2, jj, kk, ll, ic)
      scal = maxval(abs(c(1:n)))
      if (scal <= 0.0_dp) scal = 1.0_dp
      do m = 1, n
         ncmp = ncmp + 1
         call note(abs(c(m)-f(m))/scal, nr, what, ibb, ii2, jj, kk, ll, m)
      end do
   end subroutine cmpz

end program catalogue_check''')
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    builddir = sys.argv[1] if len(sys.argv) > 1 else "build"
    out = sys.argv[2] if len(sys.argv) > 2 else \
          os.path.join(HERE, "catalogue_check.F90")
    es = collect(builddir)
    emit(es, out)
    print(f"{len(es)} entry points -> {out}")
