   real(dp) :: mat(NAO, NAO)
   real(dp), allocatable :: blk(:)
   real(dp) :: worst, wabs, d, denom, scale
   integer :: ish, jsh, di, dj, i0, j0, i, r, cc, hv, nbad

   mat = 0.0_dp
   do ish = 0, NBAS - 1
      do jsh = 0, NBAS - 1
         di = (2*BAS(ANG_OF + ish*BAS_SLOTS) + 1)*BAS(NCTR_OF + ish*BAS_SLOTS)
         dj = (2*BAS(ANG_OF + jsh*BAS_SLOTS) + 1)*BAS(NCTR_OF + jsh*BAS_SLOTS)
         allocate (blk(0:di*dj - 1))
         blk = 0.0_dp
         hv = ecp_scalar_sph(blk, [ish, jsh], ATM, NATM, BAS, NBAS, ENV)
         i0 = AO_LOC(ish)
         j0 = AO_LOC(jsh)
         do i = 0, dj - 1
            mat(i0 + 1:i0 + di, j0 + 1 + i) = blk(i*di:i*di + di - 1)
         end do
         deallocate (blk)
      end do
   end do

   worst = 0.0_dp
   wabs = 0.0_dp
   scale = 0.0_dp
   nbad = 0
   do cc = 1, NAO
      do r = 1, NAO
         scale = max(scale, abs(REF((cc - 1)*NAO + r)))
      end do
   end do
   ! A matrix of zeros would make the test vacuous rather than passing, which
   ! is a mistake worth failing on: asking for an ECP the basis does not
