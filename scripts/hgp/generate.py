#!/usr/bin/env python3
"""Generate src/hgp/*.f90 (one module per class), src/cint_hgp_kernels.f90
(the dispatcher) and src/hgp/kernels.cmake.

    python3 scripts/hgp/generate.py [--lmax 2] [--no-L] [--root <checkout>]

Classes are canonical for HGP: the transfers move momentum from A onto B
and from C onto D, so the higher kind goes first in each pair, and the
higher pair goes first -- the reverse of the rotated-axis convention.
"""

import argparse
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from hgp.emit import ClassPlan, emit_class_file, cname, class_code, \
                     GradClassPlan, emit_grad_kernel
from hgp.kinds import KIND_RANK, KIND_LMAX


def canonical_classes(lmax, with_L=True):
    kinds = [k for k in sorted(KIND_RANK, key=KIND_RANK.get, reverse=True)
             if KIND_LMAX[k] <= lmax and (with_L or k != "L")]
    pairs = [(a, b) for i, a in enumerate(kinds) for b in kinds[i:]]
    return [p + q for i, p in enumerate(pairs) for q in pairs[i:]]


DISPATCH_HEAD = """! GENERATED by scripts/hgp -- do not edit.
!
! Obara-Saika/Head-Gordon-Pople two-electron kernels: the dispatcher.
!
! One module per canonical class of shell kinds in src/hgp/.  The vertical
! recurrence builds [e0|f0] -- all angular momentum on A and C -- inside
! the primitive loop; those are contracted; the horizontal recurrences then
! move momentum onto B and D once per contracted quartet, using A-B and
! C-D alone.  doc/HGP.md has the derivation, and scripts/hgp/check_numeric.py
! checks the recurrences against McMurchie-Davidson before any of this is
! emitted.
!
! Classes are canonical with the higher kind first in each pair, which is
! the direction the transfers run.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lmax", type=int, default=2)
    ap.add_argument("--no-L", action="store_true")
    ap.add_argument("--summary", action="store_true")
    ap.add_argument("--grad", action="store_true",
                    help="emit the gradient kernels (d/dA, libcint int2e_ip1 layout)")
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))))
    args = ap.parse_args()

    if args.grad:
        # No canonicalisation: d/dA names one centre, so the caller's slot 0
        # stays slot 0 and every ORDERED combination needs its own kernel --
        # the same constraint the rotated-axis gradients have.
        kinds = [k for k in sorted(KIND_RANK, key=KIND_RANK.get, reverse=True)
                 if KIND_LMAX[k] <= args.lmax and (not args.no_L or k != "L")]
        classes = [(a, b, c, d) for a in kinds for b in kinds
                   for c in kinds for d in kinds]
        plans = [GradClassPlan(k) for k in classes]
    else:
        classes = canonical_classes(args.lmax, not args.no_L)
        plans = [ClassPlan(k) for k in classes]
    for p in plans:
        print(p.summary(), file=sys.stderr)
    if args.summary:
        return

    files = {}
    if args.grad:
        for p in plans:
            nm = f"hgp_grad_{cname(p.kinds)}"
            files[f"src/hgp_grad/{nm}.f90"] = "\n".join([
                "! GENERATED by scripts/hgp -- do not edit.",
                f"! {p.summary()}",
                f"module {nm}_m",
                "   use cint_const, only: dp",
                "   use cint_rotaxis_boys, only: boys",
                "   implicit none",
                "   private",
                f"   public :: {nm}",
                "   real(dp), parameter :: PI = 3.14159265358979323846_dp",
                "   real(dp), parameter :: TWO_PI_52 = 2.0_dp*PI**2*sqrt(PI)",
                "contains",
                emit_grad_kernel(p),
                f"end module {nm}_m"]) + "\n"
    else:
        for p in plans:
            files[f"src/hgp/hgp_{cname(p.kinds)}.f90"] = emit_class_file(p)

    tag  = "grad_" if args.grad else ""
    mdir = "hgp_grad" if args.grad else "hgp"
    o = [DISPATCH_HEAD]
    for p in plans:
        o.append(f"!   {p.summary()}")
    o.append(f"module cint_hgp_{tag}kernels")
    o.append("   use cint_const, only: dp")
    for p in plans:
        n = f"hgp_{tag}{cname(p.kinds)}"
        o.append(f"   use {n}_m, only: {n}")
    o.append("   implicit none")
    o.append("   private")
    o.append(f"   public :: hgp_{tag}kernel, hgp_{tag}has_class")
    lmax = max(KIND_LMAX[x] for k in classes for x in k)
    o.append(f"   integer, parameter, public :: HGP_LMAX = {lmax}")
    o.append("   ! Kind ranks, the digits of the class code: s, p, L, d.")
    o.append("   integer, parameter, public :: HGP_KIND_S = 0, HGP_KIND_P = 1, &")
    o.append("                                 HGP_KIND_L = 2, HGP_KIND_D = 3")
    o.append("")
    o.append("contains")
    o.append("")
    o.append(f"   pure logical function hgp_{tag}has_class(code) result(yes)")
    o.append("      integer, intent(in) :: code")
    o.append("      select case (code)")
    codes = [str(class_code(k)) for k in classes]
    o.append("      case (" + ", &\n            ".join(
        ", ".join(codes[i:i+12]) for i in range(0, len(codes), 12)) + ")")
    o.append("         yes = .true.")
    o.append("      case default")
    o.append("         yes = .false.")
    o.append("      end select")
    o.append(f"   end function hgp_{tag}has_class")
    o.append("")
    o.append(f"   subroutine hgp_{tag}kernel(code, nbra, ncb, bp, kab, nket, nck, kp, kcd, &")
    o.append("                         ab, cd, cutoff, res, any)")
    o.append("      integer,  intent(in)  :: code, nbra, ncb, nket, nck")
    o.append(f"      real(dp), intent(in)  :: bp({11 if args.grad else 10}, nbra), kab(*)")
    o.append(f"      real(dp), intent(in)  :: kp({11 if args.grad else 10}, nket), kcd(*), ab(3), cd(3), cutoff")
    o.append("      real(dp), intent(out) :: res(*)")
    o.append("      logical,  intent(out) :: any")
    o.append("      select case (code)")
    for k in classes:
        o.append(f"      case ({class_code(k)})")
        o.append(f"         call hgp_{tag}{cname(k)}(nbra, ncb, bp, kab, nket, nck, kp, kcd, &")
        o.append("                             ab, cd, cutoff, res, any)")
    o.append("      case default")
    o.append("         error stop 'cint_hgp_kernels: no kernel for this class'")
    o.append("      end select")
    o.append(f"   end subroutine hgp_{tag}kernel")
    o.append(f"end module cint_hgp_{tag}kernels")
    files[f"src/cint_hgp_{tag}kernels.f90"] = "\n".join(o) + "\n"

    cm = ["# GENERATED by scripts/hgp -- do not edit.",
          f"set(cintHgp{'Grad' if args.grad else ''}Src"]
    cm += [f"  {mdir}/{p.split('/')[-1]}" for p in files if p.startswith(f"src/{mdir}/")]
    cm.append(")")
    files[f"src/{mdir}/kernels.cmake"] = "\n".join(cm) + "\n"

    for stale in glob.glob(os.path.join(args.root, "src", mdir, "hgp_*.f90")):
        os.remove(stale)
    for rel, text in files.items():
        path = os.path.join(args.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            fh.write(text)
    print(f"wrote {len(files)} files", file=sys.stderr)


if __name__ == "__main__":
    main()
