#!/usr/bin/env python3
"""Re-emit src/roots_xw.dat, the Slater-type-geminal quadrature table, as a
Fortran module.

    python3 scripts/stg_roots_to_fortran.py --out fortran/src

WHY THIS ONE IS GENERATED AT BUILD TIME AND NOT COMMITTED
---------------------------------------------------------
Every other table in this port is committed, so a build needs no Python.
This one is not, and the reason is size: roots_xw.dat is 100 MB of C source
holding 3,567,200 doubles.  Committing a Fortran copy would double that for
a feature that is off by default upstream and off by default here.

The cost of generating it is measured rather than guessed.  gfortran's time
and memory on a constant array are linear in the element count -- 250k took
3.5 s and 330 MB, 500k took 7.4 s and 644 MB, 1M took 15.3 s and 1.27 GB --
so the whole table lands near a minute and 4.5 GB.  That is a real cost, and
it falls only on someone who asks for WITH_F12.

The transform is syntactic, for the same reason the other tables are: the
committed C is what the shipped library actually uses, and a syntax
transform is bitwise-identical by construction where a regeneration from
libslater would have to be argued.
"""

import argparse
import os
import re
import sys

HEADER = """!
! The Slater-type-geminal quadrature table, from src/roots_xw.dat.
!
! Generated by scripts/stg_roots_to_fortran.py -- do not edit, and do not
! commit: it is 100 MB of source for a feature that is off by default.  See
! that script for why this one table is treated differently from every other
! one in the port.
!
! Laid out exactly as the C's DATA_X and DATA_W, so CINTstg_roots' index
! arithmetic -- (nroots-1)*nroots/2 * 19600, then nroots*196*(iu + it*10) --
! carries over unchanged.
!
module cint_tab_stg_roots
   use cint_const, only: dp
   implicit none
   public
"""


def read_arrays(path):
    """Return {'DATA_X': [str, ...], 'DATA_W': [...]} of literal tokens."""
    arrays = {}
    name = None
    vals = None
    num = re.compile(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?")
    with open(path) as fh:
        for line in fh:
            m = re.match(r"\s*static const double (\w+)\[\]\s*=\s*\{", line)
            if m:
                if name is not None:
                    arrays[name] = vals
                name = m.group(1)
                vals = []
                continue
            if name is None:
                continue
            if line.lstrip().startswith("};"):
                arrays[name] = vals
                name = None
                vals = None
                continue
            if line.lstrip().startswith("/*"):
                continue
            vals.extend(num.findall(line))
    if name is not None:
        arrays[name] = vals
    return arrays


def emit(fh, name, vals, per_line=4):
    fh.write("   real(dp), parameter :: %s(0:%d) = [ &\n" % (name, len(vals) - 1))
    buf = []
    for i in range(0, len(vals), per_line):
        chunk = ", ".join("%s_dp" % v for v in vals[i:i + per_line])
        buf.append("      " + chunk)
    fh.write(", &\n".join(buf))
    fh.write(" ]\n\n")


FACADE = """! One name for the two tables below, so `cint_stg_roots` needs only this
! module and does not care that the data is split across two files.
!
! The split is GitHub's 100 MB per-file limit and nothing deeper: the two
! arrays together are 108 MB of source, and separately they are 54 MB each.
module cint_tab_stg_roots
   use cint_tab_stg_x, only: STG_X
   use cint_tab_stg_w, only: STG_W
   implicit none
   public :: STG_X, STG_W
end module cint_tab_stg_roots
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="fortran/src")
    ap.add_argument("--dat", default="src/roots_xw.dat")
    args = ap.parse_args()

    arrays = read_arrays(args.dat)
    for key in ("DATA_X", "DATA_W"):
        if key not in arrays:
            sys.exit("%s: no %s found" % (args.dat, key))

    # One array per file. Together they are 108 MB of Fortran and GitHub
    # refuses any single file over 100 MB, so they cannot share one.
    for mod, key, arr in (("cint_tab_stg_x", "STG_X", "DATA_X"),
                          ("cint_tab_stg_w", "STG_W", "DATA_W")):
        path = os.path.join(args.out, mod + ".f90")
        with open(path, "w") as fh:
            fh.write(HEADER.replace("cint_tab_stg_roots", mod))
            emit(fh, key, arrays[arr])
            fh.write("end module %s\n" % mod)
        print("%s: %s %d" % (path, key, len(arrays[arr])))

    path = os.path.join(args.out, "cint_tab_stg_roots.f90")
    with open(path, "w") as fh:
        fh.write(FACADE)
    print("%s: facade" % path)


if __name__ == "__main__":
    main()
