   ! (LL|pp)  L=5: 201 bra accumulators, 642 ket accumulators (3556 terms), 432 components -- table driven
   subroutine rotaxis_grad_LLpp(nbra, ncb, bp, kab, nket, nck, kp, kcd, gc, cutoff, res, any)
      integer,  intent(in)  :: nbra, ncb, nket, nck
      real(dp), intent(in)  :: bp(6, nbra), kab(4*ncb, nbra)
      real(dp), intent(in)  :: kp(7, nket), kcd(1*nck, nket), gc(3), cutoff
      real(dp), intent(out) :: res(432, ncb*nck)
      logical,  intent(out) :: any
      real(dp) :: s(201, ncb), r(642, ncb, nck), t(642)
      real(dp) :: f(0:5), b(0:5), g(16), km(24), cm(28), zqp(0:5), v
      real(dp) :: p, ip, za, zb, eab, q, iq, yc, yd, ax, az, ecd
      real(dp) :: zq, alpha, tt, w, m2a, Rs, Rc, cy, ea
      integer :: kq, bq, cc, ck, n, i, j, col

      Rs = gc(1); Rc = gc(2); cy = gc(3)
      any = .false.
      r = 0.0_dp
      do kq = 1, nket
         q = kp(1,kq); iq = kp(2,kq); yc = kp(3,kq); yd = kp(4,kq)
         ax = kp(5,kq); az = kp(6,kq); ecd = kp(7,kq)
         s = 0.0_dp
         do bq = 1, nbra
            eab = bp(5,bq)
            if (eab + ecd > cutoff) cycle
            any = .true.
            p = bp(1,bq); ip = bp(2,bq); za = bp(3,bq); zb = bp(4,bq)
            ea = bp(6,bq)
            zq = za - az
            alpha = p*q/(p + q)
            tt = alpha*(ax*ax + cy*cy + zq*zq)
            call boys(f, tt, 5)
            w = 1.0_dp/sqrt(p + q)
            m2a = -2.0_dp*alpha
            do n = 0, 5
               b(n) = w*f(n)
               w = w*m2a
            end do
            zqp(0) = 1.0_dp
            do i = 1, 5
               zqp(i) = zqp(i-1)*zq
            end do
            do i = 1, 16
               g(i) = 1.0_dp
               do j = 1, g_e(4*i-3); g(i) = g(i)*ip; end do
               do j = 1, g_e(4*i-2); g(i) = g(i)*za; end do
               do j = 1, g_e(4*i-1); g(i) = g(i)*zb; end do
               do j = 1, g_e(4*i);   g(i) = g(i)*ea; end do
            end do
            do i = 1, 201
               v = g(s_g(i))*b(s_n(i))*zqp(s_k(i))
               do cc = 1, ncb
                  s(i,cc) = s(i,cc) + kab(s_tt(i)+4*(cc-1),bq)*v
               end do
            end do
         end do
         if (.not. any) cycle
         do i = 1, 24
            km(i) = 1.0_dp
            do j = 1, km_e(4*i-3); km(i) = km(i)*iq; end do
            do j = 1, km_e(4*i-2); km(i) = km(i)*yc; end do
            do j = 1, km_e(4*i-1); km(i) = km(i)*yd; end do
            do j = 1, km_e(4*i); km(i) = km(i)*ax; end do
         end do
         do cc = 1, ncb
            t = 0.0_dp
            do i = 1, 3556
               t(rt_r(i)) = t(rt_r(i)) + real(rt_c(i), dp)/real(rt_d(i), dp)*km(rt_km(i))*s(rt_s(i),cc)
            end do
            do ck = 1, nck
               r(1:642,cc,ck) = r(1:642,cc,ck) + kcd(ck,kq)*t(1:642)
            end do
         end do
      end do
      res = 0.0_dp
      if (.not. any) return
      do i = 1, 28
         cm(i) = 1.0_dp
         do j = 1, cm_e(3*i-2); cm(i) = cm(i)*Rs; end do
         do j = 1, cm_e(3*i-1); cm(i) = cm(i)*Rc; end do
         do j = 1, cm_e(3*i); cm(i) = cm(i)*cy; end do
      end do
      do ck = 1, nck
         do cc = 1, ncb
            col = cc + ncb*(ck-1)
            do i = 1, 1535
               res(at_comp(i),col) = res(at_comp(i),col) &
                  + real(at_c(i), dp)/real(at_d(i), dp)*cm(at_cm(i))*r(at_r(i),cc,ck)
            end do
         end do
      end do
   end subroutine rotaxis_grad_LLpp

