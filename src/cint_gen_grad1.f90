   subroutine CINTgout1e_int1e_ipprinvp(gout, g, idx, envs, gout_empty)
      real(dp), intent(inout) :: gout(0:*)
      real(dp), intent(inout), target :: g(0:)
      integer,  intent(in)    :: idx(0:*)
      type(cint_env_vars), intent(in) :: envs
      integer,  intent(in)    :: gout_empty
      integer  :: nf, nroots, ix, iy, iz, i, n
      integer  :: g0, g1, g2, g3, g4, g5, g6, g7
      real(dp), pointer, contiguous :: g0p(:), g1p(:), g2p(:), g3p(:), g4p(:), g5p(:)
      real(dp), pointer, contiguous :: g6p(:), g7p(:)
      real(dp) :: s(0:26)

      nf = envs%nf
      nroots = envs%nrys_roots
      g0 = 0
      g1 = g0 + envs%g_size * 3
      g2 = g1 + envs%g_size * 3
      g3 = g2 + envs%g_size * 3
      g4 = g3 + envs%g_size * 3
      g5 = g4 + envs%g_size * 3
      g6 = g5 + envs%g_size * 3
      g7 = g6 + envs%g_size * 3
      call cint_nabla1j_2e(g, g1, g0, envs%i_l+2, envs%j_l+0, 0, 0, envs)
      call cint_nabla1i_2e(g, g2, g0, envs%i_l+1, envs%j_l, 0, 0, envs)
      call cint_nabla1i_2e(g, g3, g1, envs%i_l+1, envs%j_l, 0, 0, envs)
      call cint_nabla1i_2e(g, g4, g0, envs%i_l+0, envs%j_l, 0, 0, envs)
      call cint_nabla1i_2e(g, g5, g1, envs%i_l+0, envs%j_l, 0, 0, envs)
      call cint_nabla1i_2e(g, g6, g2, envs%i_l+0, envs%j_l, 0, 0, envs)
      call cint_nabla1i_2e(g, g7, g3, envs%i_l+0, envs%j_l, 0, 0, envs)
      g0p(0:) => g(g0:)
      g1p(0:) => g(g1:)
      g2p(0:) => g(g2:)
      g3p(0:) => g(g3:)
      g4p(0:) => g(g4:)
      g5p(0:) => g(g5:)
      g6p(0:) => g(g6:)
      g7p(0:) => g(g7:)

      do n = 0, nf - 1
         ix = idx(0+n*3)
         iy = idx(1+n*3)
         iz = idx(2+n*3)
         s = 0.0_dp
         do i = 0, nroots - 1
               s(0) = s(0) + g7p(ix+i) * g0p(iy+i) * g0p(iz+i)
               s(1) = s(1) + g6p(ix+i) * g1p(iy+i) * g0p(iz+i)
               s(2) = s(2) + g6p(ix+i) * g0p(iy+i) * g1p(iz+i)
               s(3) = s(3) + g5p(ix+i) * g2p(iy+i) * g0p(iz+i)
               s(4) = s(4) + g4p(ix+i) * g3p(iy+i) * g0p(iz+i)
               s(5) = s(5) + g4p(ix+i) * g2p(iy+i) * g1p(iz+i)
               s(6) = s(6) + g5p(ix+i) * g0p(iy+i) * g2p(iz+i)
               s(7) = s(7) + g4p(ix+i) * g1p(iy+i) * g2p(iz+i)
               s(8) = s(8) + g4p(ix+i) * g0p(iy+i) * g3p(iz+i)
               s(9) = s(9) + g3p(ix+i) * g4p(iy+i) * g0p(iz+i)
               s(10) = s(10) + g2p(ix+i) * g5p(iy+i) * g0p(iz+i)
               s(11) = s(11) + g2p(ix+i) * g4p(iy+i) * g1p(iz+i)
               s(12) = s(12) + g1p(ix+i) * g6p(iy+i) * g0p(iz+i)
               s(13) = s(13) + g0p(ix+i) * g7p(iy+i) * g0p(iz+i)
               s(14) = s(14) + g0p(ix+i) * g6p(iy+i) * g1p(iz+i)
               s(15) = s(15) + g1p(ix+i) * g4p(iy+i) * g2p(iz+i)
               s(16) = s(16) + g0p(ix+i) * g5p(iy+i) * g2p(iz+i)
               s(17) = s(17) + g0p(ix+i) * g4p(iy+i) * g3p(iz+i)
               s(18) = s(18) + g3p(ix+i) * g0p(iy+i) * g4p(iz+i)
               s(19) = s(19) + g2p(ix+i) * g1p(iy+i) * g4p(iz+i)
               s(20) = s(20) + g2p(ix+i) * g0p(iy+i) * g5p(iz+i)
               s(21) = s(21) + g1p(ix+i) * g2p(iy+i) * g4p(iz+i)
               s(22) = s(22) + g0p(ix+i) * g3p(iy+i) * g4p(iz+i)
               s(23) = s(23) + g0p(ix+i) * g2p(iy+i) * g5p(iz+i)
