      g2 = g1 + envs%g_size * 3
      g3 = g2 + envs%g_size * 3
      call cint_nabla1j_1e(g, g1, g0, envs%i_l+1, envs%j_l+0, 0, envs)
      g2 = g0 + envs%g_stride_i
      g3 = g1 + envs%g_stride_i
      g0p(0:) => g(g0:)
      g1p(0:) => g(g1:)
      g2p(0:) => g(g2:)
