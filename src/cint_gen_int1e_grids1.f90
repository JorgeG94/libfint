   subroutine CINTgout1e_int1e_grids_ipip(gout, g, idx, envs, gout_empty)
      real(dp), intent(inout) :: gout(0:*)
      real(dp), intent(inout), target :: g(0:)
      integer,  intent(in)    :: idx(0:*)
      type(cint_env_vars), intent(in) :: envs
      integer,  intent(in)    :: gout_empty
      integer  :: ngrids, bgrids, nroots, nf, ix, iy, iz, n, i, ig
      integer  :: g0, g1, g2, g3
      real(dp), pointer, contiguous :: g0p(:), g1p(:), g2p(:), g3p(:)
      real(dp) :: s(0:GRID_BLKSIZE*9 - 1)

      ngrids = envs%nfl
      bgrids = min(ngrids - envs%nfk, GRID_BLKSIZE)
      nroots = envs%nrys_roots
      nf = envs%nf
      g0 = 0
      g1 = g0 + envs%g_size * 3
      g2 = g1 + envs%g_size * 3
      g3 = g2 + envs%g_size * 3
      call cint_nabla1i_grids(g, g1, g0, envs%i_l+1, envs%j_l, envs)
      call cint_nabla1i_grids(g, g2, g0, envs%i_l+0, envs%j_l, envs)
      call cint_nabla1i_grids(g, g3, g1, envs%i_l+0, envs%j_l, envs)
      g0p(0:) => g(g0:)
      g1p(0:) => g(g1:)
      g2p(0:) => g(g2:)
      g3p(0:) => g(g3:)

      do n = 0, nf - 1
         ix = idx(0+n*3)
         iy = idx(1+n*3)
         iz = idx(2+n*3)
         do i = 0, 9 - 1
            do ig = 0, bgrids - 1
               s(ig+i*GRID_BLKSIZE) = 0.0_dp
            end do
         end do
         do i = 0, nroots - 1
            do ig = 0, bgrids - 1
               s(ig+GRID_BLKSIZE*0) = s(ig+GRID_BLKSIZE*0) &
                  + g3p(ix+ig+i*GRID_BLKSIZE) * g0p(iy+ig+i*GRID_BLKSIZE) &
                  * g0p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*1) = s(ig+GRID_BLKSIZE*1) &
                  + g2p(ix+ig+i*GRID_BLKSIZE) * g1p(iy+ig+i*GRID_BLKSIZE) &
                  * g0p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*2) = s(ig+GRID_BLKSIZE*2) &
                  + g2p(ix+ig+i*GRID_BLKSIZE) * g0p(iy+ig+i*GRID_BLKSIZE) &
                  * g1p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*3) = s(ig+GRID_BLKSIZE*3) &
                  + g1p(ix+ig+i*GRID_BLKSIZE) * g2p(iy+ig+i*GRID_BLKSIZE) &
                  * g0p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*4) = s(ig+GRID_BLKSIZE*4) &
                  + g0p(ix+ig+i*GRID_BLKSIZE) * g3p(iy+ig+i*GRID_BLKSIZE) &
                  * g0p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*5) = s(ig+GRID_BLKSIZE*5) &
                  + g0p(ix+ig+i*GRID_BLKSIZE) * g2p(iy+ig+i*GRID_BLKSIZE) &
                  * g1p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*6) = s(ig+GRID_BLKSIZE*6) &
                  + g1p(ix+ig+i*GRID_BLKSIZE) * g0p(iy+ig+i*GRID_BLKSIZE) &
                  * g2p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*7) = s(ig+GRID_BLKSIZE*7) &
                  + g0p(ix+ig+i*GRID_BLKSIZE) * g1p(iy+ig+i*GRID_BLKSIZE) &
                  * g2p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*8) = s(ig+GRID_BLKSIZE*8) &
                  + g0p(ix+ig+i*GRID_BLKSIZE) * g0p(iy+ig+i*GRID_BLKSIZE) &
                  * g3p(iz+ig+i*GRID_BLKSIZE)
            end do
         end do
         if (gout_empty /= 0) then
            do ig = 0, bgrids - 1
               gout(ig+bgrids*(n*9+0)) = + s(ig+GRID_BLKSIZE*0)
               gout(ig+bgrids*(n*9+1)) = + s(ig+GRID_BLKSIZE*3)
               gout(ig+bgrids*(n*9+2)) = + s(ig+GRID_BLKSIZE*6)
               gout(ig+bgrids*(n*9+3)) = + s(ig+GRID_BLKSIZE*1)
               gout(ig+bgrids*(n*9+4)) = + s(ig+GRID_BLKSIZE*4)
               gout(ig+bgrids*(n*9+5)) = + s(ig+GRID_BLKSIZE*7)
               gout(ig+bgrids*(n*9+6)) = + s(ig+GRID_BLKSIZE*2)
               gout(ig+bgrids*(n*9+7)) = + s(ig+GRID_BLKSIZE*5)
               gout(ig+bgrids*(n*9+8)) = + s(ig+GRID_BLKSIZE*8)
            end do
         else
            do ig = 0, bgrids - 1
               gout(ig+bgrids*(n*9+0)) = gout(ig+bgrids*(n*9+0)) + ( + s(ig+GRID_BLKSIZE*0) )
               gout(ig+bgrids*(n*9+1)) = gout(ig+bgrids*(n*9+1)) + ( + s(ig+GRID_BLKSIZE*3) )
               gout(ig+bgrids*(n*9+2)) = gout(ig+bgrids*(n*9+2)) + ( + s(ig+GRID_BLKSIZE*6) )
               gout(ig+bgrids*(n*9+3)) = gout(ig+bgrids*(n*9+3)) + ( + s(ig+GRID_BLKSIZE*1) )
               gout(ig+bgrids*(n*9+4)) = gout(ig+bgrids*(n*9+4)) + ( + s(ig+GRID_BLKSIZE*4) )
               gout(ig+bgrids*(n*9+5)) = gout(ig+bgrids*(n*9+5)) + ( + s(ig+GRID_BLKSIZE*7) )
               gout(ig+bgrids*(n*9+6)) = gout(ig+bgrids*(n*9+6)) + ( + s(ig+GRID_BLKSIZE*2) )
               gout(ig+bgrids*(n*9+7)) = gout(ig+bgrids*(n*9+7)) + ( + s(ig+GRID_BLKSIZE*5) )
               gout(ig+bgrids*(n*9+8)) = gout(ig+bgrids*(n*9+8)) + ( + s(ig+GRID_BLKSIZE*8) )
            end do
         end if
      end do
   end subroutine CINTgout1e_int1e_grids_ipip

