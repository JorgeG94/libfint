                  + g0p(ix+ig+i*GRID_BLKSIZE) * g2p(iy+ig+i*GRID_BLKSIZE) &
                  * g1p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*6) = s(ig+GRID_BLKSIZE*6) &
                  + g1p(ix+ig+i*GRID_BLKSIZE) * g0p(iy+ig+i*GRID_BLKSIZE) &
                  * g2p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*7) = s(ig+GRID_BLKSIZE*7) &
                  + g0p(ix+ig+i*GRID_BLKSIZE) * g1p(iy+ig+i*GRID_BLKSIZE) &
                  * g2p(iz+ig+i*GRID_BLKSIZE)
               s(ig+GRID_BLKSIZE*8) = s(ig+GRID_BLKSIZE*8) &
                  + g0p(ix+ig+i*GRID_BLKSIZE) * g0p(iy+ig+i*GRID_BLKSIZE) &
                  * g3p(iz+ig+i*GRID_BLKSIZE)
            end do
         end do
         if (gout_empty /= 0) then
            do ig = 0, bgrids - 1
               gout(ig+bgrids*(n*4+0)) = + s(ig+GRID_BLKSIZE*5) - s(ig+GRID_BLKSIZE*7)
               gout(ig+bgrids*(n*4+1)) = + s(ig+GRID_BLKSIZE*6) - s(ig+GRID_BLKSIZE*2)
               gout(ig+bgrids*(n*4+2)) = + s(ig+GRID_BLKSIZE*1) - s(ig+GRID_BLKSIZE*3)
               gout(ig+bgrids*(n*4+3)) = + s(ig+GRID_BLKSIZE*0) + s(ig+GRID_BLKSIZE*4) &
                        + s(ig+GRID_BLKSIZE*8)
            end do
         else
            do ig = 0, bgrids - 1
               gout(ig+bgrids*(n*4+0)) = gout(ig+bgrids*(n*4+0)) + ( + s(ig+GRID_BLKSIZE*5) &
                        - s(ig+GRID_BLKSIZE*7) )
               gout(ig+bgrids*(n*4+1)) = gout(ig+bgrids*(n*4+1)) + ( + s(ig+GRID_BLKSIZE*6) &
                        - s(ig+GRID_BLKSIZE*2) )
               gout(ig+bgrids*(n*4+2)) = gout(ig+bgrids*(n*4+2)) + ( + s(ig+GRID_BLKSIZE*1) &
                        - s(ig+GRID_BLKSIZE*3) )
               gout(ig+bgrids*(n*4+3)) = gout(ig+bgrids*(n*4+3)) + ( + s(ig+GRID_BLKSIZE*0) &
                        + s(ig+GRID_BLKSIZE*4) + s(ig+GRID_BLKSIZE*8) )
            end do
         end if
      end do
   end subroutine CINTgout1e_int1e_grids_spvsp

