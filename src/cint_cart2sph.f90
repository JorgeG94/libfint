!
! Cartesian-to-spherical transforms.
!
! Generated by scripts/c_cart2sph_to_fortran.py from src/cart2sph.c -- do not
! edit.  The sparse coefficient pattern is read out of the C's hand-unrolled
! bra transforms, and both the bra and the ket loops are emitted from it, so
! the two cannot drift apart.
!
! l = 0..4 are unrolled, as in the C, which is what ordinary basis sets use.
! Above that the general form applies the transform as a small matrix product
! -- see cint_c2s_general below.
!
! The spinor transforms are NOT here; they belong with the rest of the
! relativistic runtime in D9.
!
module cint_cart2sph
   use cint_const,       only: dp
   use cint_tab_cart2sph, only: g_trans_cart2sph
   use cint_bas,         only: cint_len_cart
   implicit none
   private

   public :: cint_c2s_bra_sph, cint_c2s_ket_sph, cint_c2s_ket_sph_copy
   public :: cint_s2c_bra_sph
   public :: RESULT_IN_GCART, RESULT_IN_GSPH

   ! The C returns a pointer, and for s and p in the default px,py,pz order it
   ! returns the input buffer so no copy happens on the commonest shells.
   ! These flags carry that information instead: the caller reads whichever
   ! buffer is named.
   integer, parameter :: RESULT_IN_GCART = 0
   integer, parameter :: RESULT_IN_GSPH  = 1

   ! Start of each l's coefficient block within g_trans_cart2sph.
   integer, parameter :: C2S_OFFSET(0:15) = [ &
      0, 1, 10, 40, 110, 245, 476, 840, 1380, 2145, 3190, 4576, 6370, 8645, 11480, 14960 ]

contains

   ! The back transformation: 2l+1 spherical components to nf Cartesian ones.
   !
   ! CINTs2c_bra_sph in the C, where it is one dgemm against the same
   ! coefficient block the forward direction reads.  Written as a loop rather
   ! than unrolled per l, unlike cint_c2s_bra_sph above: this is called once
   ! per angular momentum when an ECP shell pair is set up and never in an
   ! inner loop, so the unrolling that earns its keep there would only be
   ! more code to get wrong here.
   !
   ! The coefficient block is indexed (m, f) at C2S_OFFSET(l) + m*nf + f,
   ! which is the same layout the forward transform reads -- the two
   ! directions differ in which index is summed over, not in the storage.
   subroutine cint_s2c_bra_sph(gsph, nket, gcart, l)
      real(dp), intent(in)  :: gsph(0:)
      real(dp), intent(out) :: gcart(0:)
      integer,  intent(in)  :: nket, l

      integer :: i, f, m, nf, nd, co
      real(dp) :: acc

      nf = cint_len_cart(l)
      nd = 2*l + 1
      co = C2S_OFFSET(l)

      do i = 0, nket - 1
         do f = 0, nf - 1
            acc = 0.0_dp
            do m = 0, nd - 1
               acc = acc + g_trans_cart2sph(co + m*nf + f) * gsph(i*nd + m)
            end do
            gcart(i*nf + f) = acc
         end do
      end do
   end subroutine cint_s2c_bra_sph

   ! Transform a bra-side block: nket columns, each of nf Cartesian
   ! components, into 2l+1 spherical ones.
   function cint_c2s_bra_sph(gsph, nket, gcart, l) result(loc)
      real(dp), intent(inout) :: gsph(0:)
      real(dp), intent(in)    :: gcart(0:)
      integer,  intent(in)    :: nket, l
      integer :: loc
      integer :: i, o, nf, nd, co

      nf = cint_len_cart(l)
      nd = 2*l + 1
      co = C2S_OFFSET(l)
      loc = RESULT_IN_GSPH

      select case (l)
      case (0)
         ! identity in the default p ordering; the C returns gcart here
         loc = RESULT_IN_GCART
      case (1)
         ! identity in the default p ordering; the C returns gcart here
         loc = RESULT_IN_GCART
      case (2)
         do i = 0, nket - 1
            o = i * 5
            gsph(o+0) = g_trans_cart2sph(co+1) * gcart(i*6+1)
            gsph(o+1) = g_trans_cart2sph(co+10) * gcart(i*6+4)
            gsph(o+2) = g_trans_cart2sph(co+12) * gcart(i*6+0) &
                 + g_trans_cart2sph(co+15) * gcart(i*6+3) &
                 + g_trans_cart2sph(co+17) * gcart(i*6+5)
            gsph(o+3) = g_trans_cart2sph(co+20) * gcart(i*6+2)
            gsph(o+4) = g_trans_cart2sph(co+24) * gcart(i*6+0) &
                 + g_trans_cart2sph(co+27) * gcart(i*6+3)
         end do
      case (3)
         do i = 0, nket - 1
            o = i * 7
            gsph(o+0) = g_trans_cart2sph(co+1) * gcart(i*10+1) &
                 + g_trans_cart2sph(co+6) * gcart(i*10+6)
            gsph(o+1) = g_trans_cart2sph(co+14) * gcart(i*10+4)
            gsph(o+2) = g_trans_cart2sph(co+21) * gcart(i*10+1) &
                 + g_trans_cart2sph(co+26) * gcart(i*10+6) &
                 + g_trans_cart2sph(co+28) * gcart(i*10+8)
            gsph(o+3) = g_trans_cart2sph(co+32) * gcart(i*10+2) &
                 + g_trans_cart2sph(co+37) * gcart(i*10+7) &
                 + g_trans_cart2sph(co+39) * gcart(i*10+9)
            gsph(o+4) = g_trans_cart2sph(co+40) * gcart(i*10+0) &
                 + g_trans_cart2sph(co+43) * gcart(i*10+3) &
                 + g_trans_cart2sph(co+45) * gcart(i*10+5)
            gsph(o+5) = g_trans_cart2sph(co+52) * gcart(i*10+2) &
                 + g_trans_cart2sph(co+57) * gcart(i*10+7)
            gsph(o+6) = g_trans_cart2sph(co+60) * gcart(i*10+0) &
                 + g_trans_cart2sph(co+63) * gcart(i*10+3)
         end do
      case (4)
         do i = 0, nket - 1
            o = i * 9
            gsph(o+0) = g_trans_cart2sph(co+1) * gcart(i*15+1) &
                 + g_trans_cart2sph(co+6) * gcart(i*15+6)
            gsph(o+1) = g_trans_cart2sph(co+19) * gcart(i*15+4) &
                 + g_trans_cart2sph(co+26) * gcart(i*15+11)
            gsph(o+2) = g_trans_cart2sph(co+31) * gcart(i*15+1) &
                 + g_trans_cart2sph(co+36) * gcart(i*15+6) &
                 + g_trans_cart2sph(co+38) * gcart(i*15+8)
            gsph(o+3) = g_trans_cart2sph(co+49) * gcart(i*15+4) &
                 + g_trans_cart2sph(co+56) * gcart(i*15+11) &
                 + g_trans_cart2sph(co+58) * gcart(i*15+13)
            gsph(o+4) = g_trans_cart2sph(co+60) * gcart(i*15+0) &
                 + g_trans_cart2sph(co+63) * gcart(i*15+3) &
                 + g_trans_cart2sph(co+65) * gcart(i*15+5) &
                 + g_trans_cart2sph(co+70) * gcart(i*15+10) &
                 + g_trans_cart2sph(co+72) * gcart(i*15+12) &
                 + g_trans_cart2sph(co+74) * gcart(i*15+14)
            gsph(o+5) = g_trans_cart2sph(co+77) * gcart(i*15+2) &
                 + g_trans_cart2sph(co+82) * gcart(i*15+7) &
                 + g_trans_cart2sph(co+84) * gcart(i*15+9)
            gsph(o+6) = g_trans_cart2sph(co+90) * gcart(i*15+0) &
                 + g_trans_cart2sph(co+95) * gcart(i*15+5) &
                 + g_trans_cart2sph(co+100) * gcart(i*15+10) &
                 + g_trans_cart2sph(co+102) * gcart(i*15+12)
            gsph(o+7) = g_trans_cart2sph(co+107) * gcart(i*15+2) &
                 + g_trans_cart2sph(co+112) * gcart(i*15+7)
            gsph(o+8) = g_trans_cart2sph(co+120) * gcart(i*15+0) &
                 + g_trans_cart2sph(co+123) * gcart(i*15+3) &
                 + g_trans_cart2sph(co+130) * gcart(i*15+10)
         end do
      case default
         call cint_c2s_general_bra(gsph, nket, gcart, nf, nd, co)
      end select
   end function cint_c2s_bra_sph

   ! Transform a ket-side block: nbra rows, strided by lds on output.
   function cint_c2s_ket_sph(gsph, gcart, lds, nbra, l) result(loc)
      real(dp), intent(inout) :: gsph(0:)
      real(dp), intent(in)    :: gcart(0:)
      integer,  intent(in)    :: lds, nbra, l
      integer :: loc
      integer :: i, nf, nd, co

      nf = cint_len_cart(l)
      nd = 2*l + 1
      co = C2S_OFFSET(l)
      loc = RESULT_IN_GSPH

      select case (l)
      case (0)
         loc = RESULT_IN_GCART
      case (1)
         loc = RESULT_IN_GCART
      case (2)
         do i = 0, nbra - 1
            gsph(0*lds+i) = g_trans_cart2sph(co+1) * gcart(1*nbra+i)
            gsph(1*lds+i) = g_trans_cart2sph(co+10) * gcart(4*nbra+i)
            gsph(2*lds+i) = g_trans_cart2sph(co+12) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+15) * gcart(3*nbra+i) &
                 + g_trans_cart2sph(co+17) * gcart(5*nbra+i)
            gsph(3*lds+i) = g_trans_cart2sph(co+20) * gcart(2*nbra+i)
            gsph(4*lds+i) = g_trans_cart2sph(co+24) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+27) * gcart(3*nbra+i)
         end do
      case (3)
         do i = 0, nbra - 1
            gsph(0*lds+i) = g_trans_cart2sph(co+1) * gcart(1*nbra+i) &
                 + g_trans_cart2sph(co+6) * gcart(6*nbra+i)
            gsph(1*lds+i) = g_trans_cart2sph(co+14) * gcart(4*nbra+i)
            gsph(2*lds+i) = g_trans_cart2sph(co+21) * gcart(1*nbra+i) &
                 + g_trans_cart2sph(co+26) * gcart(6*nbra+i) &
                 + g_trans_cart2sph(co+28) * gcart(8*nbra+i)
            gsph(3*lds+i) = g_trans_cart2sph(co+32) * gcart(2*nbra+i) &
                 + g_trans_cart2sph(co+37) * gcart(7*nbra+i) &
                 + g_trans_cart2sph(co+39) * gcart(9*nbra+i)
            gsph(4*lds+i) = g_trans_cart2sph(co+40) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+43) * gcart(3*nbra+i) &
                 + g_trans_cart2sph(co+45) * gcart(5*nbra+i)
            gsph(5*lds+i) = g_trans_cart2sph(co+52) * gcart(2*nbra+i) &
                 + g_trans_cart2sph(co+57) * gcart(7*nbra+i)
            gsph(6*lds+i) = g_trans_cart2sph(co+60) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+63) * gcart(3*nbra+i)
         end do
      case (4)
         do i = 0, nbra - 1
            gsph(0*lds+i) = g_trans_cart2sph(co+1) * gcart(1*nbra+i) &
                 + g_trans_cart2sph(co+6) * gcart(6*nbra+i)
            gsph(1*lds+i) = g_trans_cart2sph(co+19) * gcart(4*nbra+i) &
                 + g_trans_cart2sph(co+26) * gcart(11*nbra+i)
            gsph(2*lds+i) = g_trans_cart2sph(co+31) * gcart(1*nbra+i) &
                 + g_trans_cart2sph(co+36) * gcart(6*nbra+i) &
                 + g_trans_cart2sph(co+38) * gcart(8*nbra+i)
            gsph(3*lds+i) = g_trans_cart2sph(co+49) * gcart(4*nbra+i) &
                 + g_trans_cart2sph(co+56) * gcart(11*nbra+i) &
                 + g_trans_cart2sph(co+58) * gcart(13*nbra+i)
            gsph(4*lds+i) = g_trans_cart2sph(co+60) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+63) * gcart(3*nbra+i) &
                 + g_trans_cart2sph(co+65) * gcart(5*nbra+i) &
                 + g_trans_cart2sph(co+70) * gcart(10*nbra+i) &
                 + g_trans_cart2sph(co+72) * gcart(12*nbra+i) &
                 + g_trans_cart2sph(co+74) * gcart(14*nbra+i)
            gsph(5*lds+i) = g_trans_cart2sph(co+77) * gcart(2*nbra+i) &
                 + g_trans_cart2sph(co+82) * gcart(7*nbra+i) &
                 + g_trans_cart2sph(co+84) * gcart(9*nbra+i)
            gsph(6*lds+i) = g_trans_cart2sph(co+90) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+95) * gcart(5*nbra+i) &
                 + g_trans_cart2sph(co+100) * gcart(10*nbra+i) &
                 + g_trans_cart2sph(co+102) * gcart(12*nbra+i)
            gsph(7*lds+i) = g_trans_cart2sph(co+107) * gcart(2*nbra+i) &
                 + g_trans_cart2sph(co+112) * gcart(7*nbra+i)
            gsph(8*lds+i) = g_trans_cart2sph(co+120) * gcart(0*nbra+i) &
                 + g_trans_cart2sph(co+123) * gcart(3*nbra+i) &
                 + g_trans_cart2sph(co+130) * gcart(10*nbra+i)
         end do
      case default
         call cint_c2s_general_ket(gsph, gcart, lds, nbra, nf, nd, co)
      end select
   end function cint_c2s_ket_sph

   ! As above, but always writes to gsph even when the transform is the
   ! identity.  The C keeps these separate for callers that need the move.
   function cint_c2s_ket_sph_copy(gsph, gcart, lds, nbra, l) result(loc)
      real(dp), intent(inout) :: gsph(0:)
      real(dp), intent(in)    :: gcart(0:)
      integer,  intent(in)    :: lds, nbra, l
      integer :: loc
      integer :: i, j

      if (l <= 1) then
         do j = 0, 2*l
            do i = 0, nbra - 1
               gsph(j*lds+i) = gcart(j*nbra+i)
            end do
         end do
         loc = RESULT_IN_GSPH
      else
         loc = cint_c2s_ket_sph(gsph, gcart, lds, nbra, l)
      end if
   end function cint_c2s_ket_sph_copy

   ! General l: the transform as a small matrix product.  The C reaches this
   ! only for l >= 5 and spells it CINTdgemm_*; those are 15x9 to 28x13 blocks,
   ! where a BLAS call and a plain loop measure within a few percent of each
   ! other, so the loop stays here and the dependency does not.
   subroutine cint_c2s_general_bra(gsph, nket, gcart, nf, nd, co)
      real(dp), intent(inout) :: gsph(0:)
      real(dp), intent(in)    :: gcart(0:)
      integer,  intent(in)    :: nket, nf, nd, co
      integer  :: i, j, k
      real(dp) :: s
      do i = 0, nket - 1
         do j = 0, nd - 1
            s = 0.0_dp
            do k = 0, nf - 1
               s = s + g_trans_cart2sph(co + j*nf + k) * gcart(i*nf + k)
            end do
            gsph(i*nd + j) = s
         end do
      end do
   end subroutine cint_c2s_general_bra

   subroutine cint_c2s_general_ket(gsph, gcart, lds, nbra, nf, nd, co)
      real(dp), intent(inout) :: gsph(0:)
      real(dp), intent(in)    :: gcart(0:)
      integer,  intent(in)    :: lds, nbra, nf, nd, co
      integer  :: i, j, k
      real(dp) :: s
      do j = 0, nd - 1
         do i = 0, nbra - 1
            s = 0.0_dp
            do k = 0, nf - 1
               s = s + g_trans_cart2sph(co + j*nf + k) * gcart(k*nbra + i)
            end do
            gsph(j*lds + i) = s
         end do
      end do
   end subroutine cint_c2s_general_ket

end module cint_cart2sph
