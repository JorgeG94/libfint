   subroutine CINTgout2e_int2e_g1(gout, g, idx, envs, gout_empty)
      real(dp), intent(inout) :: gout(0:*)
      real(dp), intent(inout), target :: g(0:)
      integer,  intent(in)    :: idx(0:*)
      type(cint_env_vars), intent(in) :: envs
      integer,  intent(in)    :: gout_empty
      integer  :: nf, nroots, ix, iy, iz, i, n
      integer  :: g0, g1
      real(dp), pointer, contiguous :: g0p(:), g1p(:)
      real(dp) :: s(0:2)
      real(dp) :: rirj(0:2)
      real(dp) :: c(0:2)

      rirj = envs%ri - envs%rj
      c(0) = 1.0_dp * rirj(0)
      c(1) = 1.0_dp * rirj(1)
      c(2) = 1.0_dp * rirj(2)
      nf = envs%nf
      nroots = envs%nrys_roots
      g0 = 0
      g1 = g0 + envs%g_size * 3
      call cint_x1i_2e(g, g1, g0, envs%ri, envs%i_l+0, envs%j_l, envs%k_l, envs%l_l, envs)
      g0p(0:) => g(g0:)
      g1p(0:) => g(g1:)

      do n = 0, nf - 1
         ix = idx(0+n*3)
         iy = idx(1+n*3)
         iz = idx(2+n*3)
         select case (nroots)
         case (1)
            s(0) = + g1p(ix+0)*g0p(iy+0)*g0p(iz+0)
            s(1) = + g0p(ix+0)*g1p(iy+0)*g0p(iz+0)
            s(2) = + g0p(ix+0)*g0p(iy+0)*g1p(iz+0)
         case (2)
            s(0) = + g1p(ix+0)*g0p(iy+0)*g0p(iz+0) &
                     + g1p(ix+1)*g0p(iy+1)*g0p(iz+1)
            s(1) = + g0p(ix+0)*g1p(iy+0)*g0p(iz+0) &
                     + g0p(ix+1)*g1p(iy+1)*g0p(iz+1)
            s(2) = + g0p(ix+0)*g0p(iy+0)*g1p(iz+0) &
                     + g0p(ix+1)*g0p(iy+1)*g1p(iz+1)
         case (3)
            s(0) = + g1p(ix+0)*g0p(iy+0)*g0p(iz+0) &
                     + g1p(ix+1)*g0p(iy+1)*g0p(iz+1) &
                     + g1p(ix+2)*g0p(iy+2)*g0p(iz+2)
            s(1) = + g0p(ix+0)*g1p(iy+0)*g0p(iz+0) &
                     + g0p(ix+1)*g1p(iy+1)*g0p(iz+1) &
                     + g0p(ix+2)*g1p(iy+2)*g0p(iz+2)
            s(2) = + g0p(ix+0)*g0p(iy+0)*g1p(iz+0) &
                     + g0p(ix+1)*g0p(iy+1)*g1p(iz+1) &
                     + g0p(ix+2)*g0p(iy+2)*g1p(iz+2)
         case (4)
            s(0) = + g1p(ix+0)*g0p(iy+0)*g0p(iz+0) &
                     + g1p(ix+1)*g0p(iy+1)*g0p(iz+1) &
                     + g1p(ix+2)*g0p(iy+2)*g0p(iz+2) &
                     + g1p(ix+3)*g0p(iy+3)*g0p(iz+3)
            s(1) = + g0p(ix+0)*g1p(iy+0)*g0p(iz+0) &
                     + g0p(ix+1)*g1p(iy+1)*g0p(iz+1) &
                     + g0p(ix+2)*g1p(iy+2)*g0p(iz+2) &
                     + g0p(ix+3)*g1p(iy+3)*g0p(iz+3)
            s(2) = + g0p(ix+0)*g0p(iy+0)*g1p(iz+0) &
                     + g0p(ix+1)*g0p(iy+1)*g1p(iz+1) &
                     + g0p(ix+2)*g0p(iy+2)*g1p(iz+2) &
                     + g0p(ix+3)*g0p(iy+3)*g1p(iz+3)
         case default
            s = 0.0_dp
            do i = 0, nroots - 1
               s(0) = s(0) + g1p(ix+i) * g0p(iy+i) * g0p(iz+i)
               s(1) = s(1) + g0p(ix+i) * g1p(iy+i) * g0p(iz+i)
               s(2) = s(2) + g0p(ix+i) * g0p(iy+i) * g1p(iz+i)
            end do
         end select
         if (gout_empty /= 0) then
            gout(n*3+0) = + c(1)*s(2) - c(2)*s(1)
            gout(n*3+1) = + c(2)*s(0) - c(0)*s(2)
            gout(n*3+2) = + c(0)*s(1) - c(1)*s(0)
         else
            gout(n*3+0) = gout(n*3+0) + ( + c(1)*s(2) - c(2)*s(1) )
            gout(n*3+1) = gout(n*3+1) + ( + c(2)*s(0) - c(0)*s(2) )
            gout(n*3+2) = gout(n*3+2) + ( + c(0)*s(1) - c(1)*s(0) )
         end if
      end do
   end subroutine CINTgout2e_int2e_g1

