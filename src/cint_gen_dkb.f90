                     + g0p(ix+2)*g0p(iy+2)*g1p(iz+2) &
                     + g0p(ix+3)*g0p(iy+3)*g1p(iz+3)
         case default
            s = 0.0_dp
            do i = 0, nroots - 1
               s(0) = s(0) + g1p(ix+i) * g0p(iy+i) * g0p(iz+i)
               s(1) = s(1) + g0p(ix+i) * g1p(iy+i) * g0p(iz+i)
               s(2) = s(2) + g0p(ix+i) * g0p(iy+i) * g1p(iz+i)
            end do
         end select
         if (gout_empty /= 0) then
            gout(n*4+0) = - s(0)
            gout(n*4+1) = - s(1)
            gout(n*4+2) = - s(2)
            gout(n*4+3) = 0
         else
            gout(n*4+0) = gout(n*4+0) + ( - s(0) )
            gout(n*4+1) = gout(n*4+1) + ( - s(1) )
            gout(n*4+2) = gout(n*4+2) + ( - s(2) )
            gout(n*4+3) = gout(n*4+3) + ( 0 )
         end if
      end do
